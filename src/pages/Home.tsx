import { Link } from "react-router-dom";
import { HomePath } from "@/components/HomePath";
import { useAppStore } from "@/store";
import { isDue } from "@/lib/srs";
import { BrainCircuit, KeyRound, ChevronRight } from "lucide-react";

export default function HomePage() {
    const apiKey = useAppStore((s) => s.apiKey);
    const decks = useAppStore((s) => s.decks);
    const dueCount = decks.reduce((sum, d) => sum + d.cards.filter(isDue).length, 0);

    return (
        <div className="flex flex-col">
            <div className="max-w-md mx-auto w-full px-4 pt-4 space-y-3 empty:hidden">
                {!apiKey && (
                    <Banner to="/settings" icon={<KeyRound className="h-5 w-5" />} tone="warning"
                        title="Add your OpenAI API key"
                        text="Lessons are generated by AI. Add your key in Settings to start." />
                )}
                {dueCount > 0 && (
                    <Banner to="/practice" icon={<BrainCircuit className="h-5 w-5" />} tone="info"
                        title={`${dueCount} ${dueCount === 1 ? 'word' : 'words'} due for review`}
                        text="A quick review now keeps them from slipping." />
                )}
            </div>
            <HomePath />
        </div>
    );
}

function Banner({ to, icon, title, text, tone }: { to: string; icon: React.ReactNode; title: string; text: string; tone: 'warning' | 'info' }) {
    return (
        <Link
            to={to}
            className={
                "flex items-center gap-3 rounded-xl border p-3 transition-colors " +
                (tone === 'warning'
                    ? "bg-amber-50 border-amber-200 text-amber-900 hover:bg-amber-100 dark:bg-amber-950/40 dark:border-amber-900 dark:text-amber-100"
                    : "bg-primary/5 border-primary/20 hover:bg-primary/10")
            }
        >
            <div className="shrink-0">{icon}</div>
            <div className="flex-1 min-w-0">
                <p className="font-semibold text-sm">{title}</p>
                <p className="text-xs opacity-80">{text}</p>
            </div>
            <ChevronRight className="h-4 w-4 shrink-0 opacity-60" />
        </Link>
    );
}
